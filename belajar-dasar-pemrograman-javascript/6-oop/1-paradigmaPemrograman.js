/* 
 * Paradigma pemrograman adalah gaya atau pendekatan yang dilakukan oleh programmer dalam menulis program.
 * Paradigma dapat menjadi pedoman dalam menulis program
 * Paradigma juga memberikan pandangan yang unik dalam menyelesaikan masalah.
 * Seperti paradigma OOP memberikan pandangan bahwa menyelesaikan masalah dpt dilakukan dgn pendekatan berbasis objek.
 * Untuk menyelesaikan masalah dgn solusi yg optimal, kita harus memiliki berbagai macam pendekatan atau pandangan.
 * Setiap paradigma menawarkan pendekatan unik yang dapat menghasilkan solusi yang optimal.
 * Dengan menulis kode sesuai paradigma yang ada:
    * Kode akan lebih bersih, 
    * Dapat digunakan kembali (reuse), dan 
    * Memudahkan berkolaborasi dengan orang lain.
 * Kolaborasi akan lebih mudah dan minim masalah karena kita memiliki pemahaman dan pedoman yang sama.
    * Misalnya, ketika menggunakan paradigma OOP,
      * setiap orang yang terlibat di projek tersebut akan menggunakan pendekatan OOP dalam menyelesaikan masalah,
      * sehingga miskomunikasi dapat dihindari.
 * Perlu diingat bahwa paradigma bukanlah rule yg wajib diikuti tetapi pedoman yg dpt memudahkan kita dlm menulis program.
 * Ada berbagai jenis paradigma pemrograman seperti imperative, object-oriented, procedural, dan functional.
*/