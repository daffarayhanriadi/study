// Setiap JSDoc comment harus dimulai dengan /** (selain dari itu, tidak akan di proses oleh JSDoc)
// Contoh JSDoc comment sederhana
/** Say hello to world */
function greet() {
  console.log("Hello, world!");
}

// Contoh JSDoc comment complex
/**
  * Get add operation of two numbers.
  *
  * @param {number} numA - The first numeric operand
  * @param {number} numB - The second numeric operand
  * @returns {number} Sum of numA and numB
  */
function add(numA, numB) {
  return numA + numB;
}


